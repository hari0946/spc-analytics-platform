-- METADATA schema. NOTE: Snowflake enforces only NOT NULL; PK/UNIQUE/FK are informational.
-- Referential integrity and uniqueness are enforced by the service layer.
USE SCHEMA SPC_PLATFORM.METADATA;

CREATE TABLE IF NOT EXISTS USERS (
    USER_ID       VARCHAR      NOT NULL DEFAULT UUID_STRING(),
    USERNAME      VARCHAR      NOT NULL,
    EMAIL         VARCHAR      NOT NULL,
    PASSWORD_HASH VARCHAR      NOT NULL,
    FULL_NAME     VARCHAR,
    IS_ACTIVE     BOOLEAN      NOT NULL DEFAULT TRUE,
    LAST_LOGIN_AT TIMESTAMP_NTZ,
    CREATED_AT    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE IF NOT EXISTS ROLES (
    ROLE_ID     VARCHAR NOT NULL DEFAULT UUID_STRING(),
    ROLE_NAME   VARCHAR NOT NULL,
    DESCRIPTION VARCHAR,
    PERMISSIONS VARIANT,
    CREATED_AT  TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_ROLES PRIMARY KEY (ROLE_ID),
    CONSTRAINT UQ_ROLES_NAME UNIQUE (ROLE_NAME)
);

CREATE TABLE IF NOT EXISTS USER_ROLES (
    USER_ID     VARCHAR NOT NULL,
    ROLE_ID     VARCHAR NOT NULL,
    ASSIGNED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_UR_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ROLE_ID)
);

CREATE TABLE IF NOT EXISTS PLANTS (
    PLANT_ID   VARCHAR NOT NULL DEFAULT UUID_STRING(),
    PLANT_CODE VARCHAR NOT NULL,
    PLANT_NAME VARCHAR NOT NULL,
    LOCATION   VARCHAR,
    IS_ACTIVE  BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PLANTS PRIMARY KEY (PLANT_ID),
    CONSTRAINT UQ_PLANTS_CODE UNIQUE (PLANT_CODE)
);

CREATE TABLE IF NOT EXISTS PRODUCTION_LINES (
    LINE_ID    VARCHAR NOT NULL DEFAULT UUID_STRING(),
    PLANT_ID   VARCHAR NOT NULL,
    LINE_CODE  VARCHAR NOT NULL,
    LINE_NAME  VARCHAR NOT NULL,
    IS_ACTIVE  BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_LINES PRIMARY KEY (LINE_ID),
    CONSTRAINT FK_LINES_PLANT FOREIGN KEY (PLANT_ID) REFERENCES PLANTS (PLANT_ID)
);

CREATE TABLE IF NOT EXISTS ASSETS (
    ASSET_ID   VARCHAR NOT NULL DEFAULT UUID_STRING(),
    LINE_ID    VARCHAR NOT NULL,
    ASSET_CODE VARCHAR NOT NULL,
    ASSET_NAME VARCHAR NOT NULL,
    ASSET_TYPE VARCHAR,
    IS_ACTIVE  BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_ASSETS PRIMARY KEY (ASSET_ID),
    CONSTRAINT FK_ASSETS_LINE FOREIGN KEY (LINE_ID) REFERENCES PRODUCTION_LINES (LINE_ID)
);

CREATE TABLE IF NOT EXISTS TAGS (
    TAG_ID    VARCHAR NOT NULL DEFAULT UUID_STRING(),
    ASSET_ID  VARCHAR NOT NULL,
    TAG_NAME  VARCHAR NOT NULL,
    PARAMETER VARCHAR NOT NULL,          -- e.g. TEMPERATURE, PRESSURE, SPEED, FLOW
    UNIT      VARCHAR,
    LSL       FLOAT,                     -- lower specification limit
    USL       FLOAT,                     -- upper specification limit
    TARGET    FLOAT,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_TAGS PRIMARY KEY (TAG_ID),
    CONSTRAINT FK_TAGS_ASSET FOREIGN KEY (ASSET_ID) REFERENCES ASSETS (ASSET_ID)
);

CREATE TABLE IF NOT EXISTS DATASET_UPLOADS (
    UPLOAD_ID        VARCHAR NOT NULL DEFAULT UUID_STRING(),
    FILE_NAME        VARCHAR NOT NULL,
    FILE_TYPE        VARCHAR NOT NULL,        -- CSV | XLSX | XLS
    FILE_SIZE_BYTES  NUMBER(38,0),
    STAGE_PATH       VARCHAR,
    COLUMN_MAPPING   VARIANT,                 -- user-configured source->standard column map
    STATUS           VARCHAR NOT NULL DEFAULT 'UPLOADED', -- UPLOADED|LOADED_BRONZE|PROCESSING|COMPLETED|FAILED
    ROWS_RECEIVED    NUMBER(38,0),
    ROWS_REJECTED    NUMBER(38,0),
    ERROR_MESSAGE    VARCHAR,
    UPLOADED_BY      VARCHAR,                 -- USERS.USER_ID
    UPLOADED_AT      TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    COMPLETED_AT     TIMESTAMP_NTZ,
    CONSTRAINT PK_UPLOADS PRIMARY KEY (UPLOAD_ID)
);

CREATE TABLE IF NOT EXISTS ANALYSIS_HISTORY (
    ANALYSIS_ID   VARCHAR NOT NULL DEFAULT UUID_STRING(),
    UPLOAD_ID     VARCHAR,
    ANALYSIS_TYPE VARCHAR NOT NULL,           -- STATISTICS|CONTROL_CHART|CAPABILITY|...
    REQUEST_PARAMS VARIANT,
    STATUS        VARCHAR NOT NULL DEFAULT 'QUEUED', -- QUEUED|RUNNING|COMPLETED|FAILED
    REQUESTED_BY  VARCHAR,
    ERROR_MESSAGE VARCHAR,
    CREATED_AT    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    STARTED_AT    TIMESTAMP_NTZ,
    COMPLETED_AT  TIMESTAMP_NTZ,
    CONSTRAINT PK_ANALYSIS_HISTORY PRIMARY KEY (ANALYSIS_ID),
    CONSTRAINT FK_AH_UPLOAD FOREIGN KEY (UPLOAD_ID) REFERENCES DATASET_UPLOADS (UPLOAD_ID)
);
