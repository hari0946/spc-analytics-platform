-- SPC_RESULTS: every row is tied to an ANALYSIS_ID (METADATA.ANALYSIS_HISTORY)
CREATE TABLE IF NOT EXISTS SPC_PLATFORM.SPC_RESULTS.ANALYSIS_RESULTS (
    RESULT_ID   VARCHAR NOT NULL DEFAULT UUID_STRING(),
    ANALYSIS_ID VARCHAR NOT NULL,
    RESULT_TYPE VARCHAR NOT NULL,
    RESULT_JSON VARIANT NOT NULL,             -- full result payload (chart points, etc.)
    CREATED_AT  TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_ANALYSIS_RESULTS PRIMARY KEY (RESULT_ID)
);

CREATE TABLE IF NOT EXISTS SPC_PLATFORM.SPC_RESULTS.CONTROL_LIMITS (
    LIMIT_ID    VARCHAR NOT NULL DEFAULT UUID_STRING(),
    ANALYSIS_ID VARCHAR NOT NULL,
    PARAMETER   VARCHAR NOT NULL,
    CHART_TYPE  VARCHAR NOT NULL,             -- XBAR|R|S|IMR|P|NP|C|U|EWMA|CUSUM
    UCL FLOAT, CL FLOAT, LCL FLOAT,
    USL FLOAT, LSL FLOAT, TARGET FLOAT,
    SUBGROUP_SIZE NUMBER(38,0),
    CREATED_AT  TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CONTROL_LIMITS PRIMARY KEY (LIMIT_ID)
);

CREATE TABLE IF NOT EXISTS SPC_PLATFORM.SPC_RESULTS.STATISTICAL_RESULTS (
    STAT_ID     VARCHAR NOT NULL DEFAULT UUID_STRING(),
    ANALYSIS_ID VARCHAR NOT NULL,
    PARAMETER   VARCHAR NOT NULL,
    N_COUNT NUMBER(38,0), MEAN_VALUE FLOAT, MEDIAN_VALUE FLOAT, MODE_VALUE FLOAT,
    MIN_VALUE FLOAT, MAX_VALUE FLOAT, RANGE_VALUE FLOAT,
    VARIANCE_VALUE FLOAT, STDDEV_VALUE FLOAT, SKEWNESS FLOAT, KURTOSIS FLOAT,
    PERCENTILES VARIANT,                      -- quartiles and other percentiles
    CREATED_AT  TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_STAT_RESULTS PRIMARY KEY (STAT_ID)
);

CREATE TABLE IF NOT EXISTS SPC_PLATFORM.SPC_RESULTS.SPC_VIOLATIONS (
    VIOLATION_ID   VARCHAR NOT NULL DEFAULT UUID_STRING(),
    ANALYSIS_ID    VARCHAR NOT NULL,
    PARAMETER      VARCHAR NOT NULL,
    VIOLATION_TYPE VARCHAR NOT NULL,          -- OUT_OF_CONTROL|TREND|SHIFT|...
    RULE_SET       VARCHAR NOT NULL,          -- WESTERN_ELECTRIC|NELSON
    RULE_NAME      VARCHAR NOT NULL,
    OCCURRED_AT    TIMESTAMP_NTZ,
    OBSERVED_VALUE FLOAT,
    SEVERITY       VARCHAR,                   -- LOW|MEDIUM|HIGH
    POINT_INDEX    NUMBER(38,0),
    CREATED_AT     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_SPC_VIOLATIONS PRIMARY KEY (VIOLATION_ID)
);

CREATE TABLE IF NOT EXISTS SPC_PLATFORM.SPC_RESULTS.CAPABILITY_RESULTS (
    CAPABILITY_ID VARCHAR NOT NULL DEFAULT UUID_STRING(),
    ANALYSIS_ID   VARCHAR NOT NULL,
    PARAMETER     VARCHAR NOT NULL,
    CP FLOAT, CPK FLOAT, PP FLOAT, PPK FLOAT, CPU FLOAT, CPL FLOAT,
    PPM_TOTAL FLOAT, YIELD_PCT FLOAT,
    USL FLOAT, LSL FLOAT, TARGET FLOAT, SAMPLE_SIZE NUMBER(38,0),
    CREATED_AT    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CAPABILITY PRIMARY KEY (CAPABILITY_ID)
);

CREATE TABLE IF NOT EXISTS SPC_PLATFORM.SPC_RESULTS.DISTRIBUTION_RESULTS (
    DISTRIBUTION_ID VARCHAR NOT NULL DEFAULT UUID_STRING(),
    ANALYSIS_ID     VARCHAR NOT NULL,
    PARAMETER       VARCHAR NOT NULL,
    NORMALITY_TEST  VARCHAR,                  -- e.g. SHAPIRO_WILK
    TEST_STATISTIC  FLOAT,
    P_VALUE         FLOAT,
    IS_NORMAL       BOOLEAN,
    BEST_FIT_DIST   VARCHAR,
    FIT_DETAILS     VARIANT,                  -- fitted params, histogram bins, probability-plot data
    CREATED_AT      TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DISTRIBUTION PRIMARY KEY (DISTRIBUTION_ID)
);
