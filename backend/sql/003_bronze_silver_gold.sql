-- BRONZE: raw rows kept as received (every source column preserved in RAW_RECORD, values as text)
CREATE TABLE IF NOT EXISTS SPC_PLATFORM.BRONZE.RAW_SENSOR_DATA (
    RAW_ID     NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    UPLOAD_ID  VARCHAR NOT NULL,
    SOURCE_ROW NUMBER(38,0) NOT NULL,          -- row number in the uploaded file
    RAW_RECORD VARIANT NOT NULL,
    LOADED_AT  TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_RAW_SENSOR PRIMARY KEY (RAW_ID)
);

CREATE TABLE IF NOT EXISTS SPC_PLATFORM.BRONZE.RAW_PRODUCTION_DATA (
    RAW_ID     NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    UPLOAD_ID  VARCHAR NOT NULL,
    SOURCE_ROW NUMBER(38,0) NOT NULL,
    RAW_RECORD VARIANT NOT NULL,
    LOADED_AT  TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_RAW_PRODUCTION PRIMARY KEY (RAW_ID)
);

-- SILVER: typed, validated, standardized
CREATE TABLE IF NOT EXISTS SPC_PLATFORM.SILVER.CLEAN_SENSOR_DATA (
    UPLOAD_ID    VARCHAR NOT NULL,
    SOURCE_ROW   NUMBER(38,0) NOT NULL,
    PLANT_CODE   VARCHAR,
    LINE_CODE    VARCHAR,
    ASSET_CODE   VARCHAR,
    TAG_NAME     VARCHAR,
    PARAMETER    VARCHAR NOT NULL,
    MEASURED_AT  TIMESTAMP_NTZ NOT NULL,
    VALUE        FLOAT NOT NULL,
    BATCH_ID     VARCHAR,
    PROCESSED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CLEAN_SENSOR PRIMARY KEY (UPLOAD_ID, SOURCE_ROW)
);

CREATE TABLE IF NOT EXISTS SPC_PLATFORM.SILVER.VALIDATED_PRODUCTION_DATA (
    UPLOAD_ID        VARCHAR NOT NULL,
    SOURCE_ROW       NUMBER(38,0) NOT NULL,
    PLANT_CODE       VARCHAR,
    LINE_CODE        VARCHAR,
    ASSET_CODE       VARCHAR,
    BATCH_ID         VARCHAR,
    PRODUCT          VARCHAR,
    EVENT_TIME       TIMESTAMP_NTZ NOT NULL,
    UNITS_PRODUCED   NUMBER(38,0),
    SAMPLE_SIZE      NUMBER(38,0),             -- n for P/NP/U charts
    DEFECTIVE_COUNT  NUMBER(38,0),             -- nonconforming units (P/NP)
    DEFECT_COUNT     NUMBER(38,0),             -- nonconformities (C/U)
    PROCESSED_AT     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_VALIDATED_PROD PRIMARY KEY (UPLOAD_ID, SOURCE_ROW)
);

-- GOLD: analysis-ready
CREATE TABLE IF NOT EXISTS SPC_PLATFORM.GOLD.GOLD_SENSOR_DATA (
    UPLOAD_ID   VARCHAR NOT NULL,
    PLANT_CODE  VARCHAR,
    LINE_CODE   VARCHAR,
    ASSET_CODE  VARCHAR,
    TAG_NAME    VARCHAR,
    PARAMETER   VARCHAR NOT NULL,
    MEASURED_AT TIMESTAMP_NTZ NOT NULL,
    VALUE       FLOAT NOT NULL,
    BATCH_ID    VARCHAR,
    SUBGROUP_ID NUMBER(38,0)                   -- subgroup index for X-bar/R/S charts
)
CLUSTER BY (UPLOAD_ID, PARAMETER, MEASURED_AT);

CREATE TABLE IF NOT EXISTS SPC_PLATFORM.GOLD.GOLD_PRODUCTION_DATA (
    UPLOAD_ID       VARCHAR NOT NULL,
    PLANT_CODE      VARCHAR,
    LINE_CODE       VARCHAR,
    ASSET_CODE      VARCHAR,
    BATCH_ID        VARCHAR,
    PRODUCT         VARCHAR,
    EVENT_TIME      TIMESTAMP_NTZ NOT NULL,
    UNITS_PRODUCED  NUMBER(38,0),
    SAMPLE_SIZE     NUMBER(38,0),
    DEFECTIVE_COUNT NUMBER(38,0),
    DEFECT_COUNT    NUMBER(38,0)
)
CLUSTER BY (UPLOAD_ID, EVENT_TIME);

-- Pre-aggregated per-parameter time buckets for fast dashboards
CREATE TABLE IF NOT EXISTS SPC_PLATFORM.GOLD.GOLD_PROCESS_DATA (
    UPLOAD_ID    VARCHAR NOT NULL,
    ASSET_CODE   VARCHAR,
    PARAMETER    VARCHAR NOT NULL,
    BUCKET_START TIMESTAMP_NTZ NOT NULL,
    BUCKET_UNIT  VARCHAR NOT NULL DEFAULT 'HOUR',
    N_POINTS     NUMBER(38,0) NOT NULL,
    MEAN_VALUE   FLOAT,
    MIN_VALUE    FLOAT,
    MAX_VALUE    FLOAT,
    STDDEV_VALUE FLOAT
)
CLUSTER BY (UPLOAD_ID, PARAMETER, BUCKET_START);
