ReportType = Literal["spc", "control_chart", "capability", "quality", "statistical"]
PDF_MAX_TABLE_ROWS = 150


@dataclass
class Table_:
    title: str
    columns: list[str]
    rows: list[list]


@dataclass
class Section:
    heading: str
    paragraphs: list[str] = field(default_factory=list)
    tables: list[Table_] = field(default_factory=list)
    images: list[bytes] = field(default_factory=list)


@dataclass
class ReportDoc:
    title: str
    meta: list[tuple[str, str]]
    sections: list[Section]


# ---------------------------------------------------------------------------------------------- charts
def _png(fig) -> bytes:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110, bbox_inches="tight")
    plt.close(fig)
    return buf.getvalue()


def chart_image(name: str, c: dict, spec: dict | None = None) -> bytes:
    fig, ax = plt.subplots(figsize=(9, 3.2))
    x = list(range(len(c["points"])))
    ax.plot(x, c["points"], color="#2563eb", lw=1, marker="o" if len(x) <= 80 else None, ms=3)
    ax.step(x, c["ucl"], where="mid", color="#dc2626", ls="--", lw=1, label="UCL")
    ax.step(x, c["cl"], where="mid", color="#16a34a", lw=1, label="CL")
    ax.step(x, c["lcl"], where="mid", color="#dc2626", ls="--", lw=1, label="LCL")
    if "lower_points" in c:
        ax.plot(x, c["lower_points"], color="#9333ea", lw=1)
    ooc = c["out_of_control"]
    if ooc:
        ax.scatter(ooc, [c["points"][i] for i in ooc], color="#dc2626", zorder=5, s=22, label="Out of control")
    for key, col in (("usl", "#ea580c"), ("lsl", "#ea580c"), ("target", "#0891b2")):
        if spec and spec.get(key) is not None:
            ax.axhline(spec[key], color=col, ls=":", lw=1, label=key.upper())
    ax.set_title(f"{name} chart", fontsize=10)
    ax.set_xlabel("Point (time order)", fontsize=8)
    ax.tick_params(labelsize=8)
    ax.legend(fontsize=7, ncol=6, loc="upper center", bbox_to_anchor=(0.5, -0.22))
    return _png(fig)


def histogram_image(h: dict, spec: dict | None = None) -> bytes:
    fig, ax = plt.subplots(figsize=(9, 3.2))
    edges = h["bin_edges"]
    ax.bar(edges[:-1], h["counts"], width=[b - a for a, b in zip(edges, edges[1:])], align="edge", color="#93c5fd", edgecolor="#2563eb")
    if h.get("normal_expected_counts"):
        ax.plot(h["bin_centers"], h["normal_expected_counts"], color="#dc2626", lw=1.2, label="Normal fit")
    for key in ("usl", "lsl", "target"):
        if spec and spec.get(key) is not None:
            ax.axvline(spec[key], color="#ea580c" if key != "target" else "#0891b2", ls="--", lw=1, label=key.upper())
    ax.set_title("Distribution of historical readings", fontsize=10)
    ax.tick_params(labelsize=8)
    ax.legend(fontsize=7)
    return _png(fig)


# ---------------------------------------------------------------------------------------------- content
def _opts(options: dict | None) -> an.ChartOptions:
    try:
        return an.ChartOptions(**(options or {}))
    except Exception as e:  # noqa: BLE001 - pydantic validation
        raise UnprocessableError(f"Invalid report options: {e}")


def _meta(kind: str, f: DataFilters, parameter: str | None, user, extra: list[tuple[str, str]] | None = None) -> list[tuple[str, str]]:
    sel = [("Report", kind), ("Generated (UTC)", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")),
           ("Generated by", user.username), ("Parameter", parameter.upper() if parameter else "—"),
           ("Datasets", ", ".join(f.upload_ids) or "all completed datasets"),
           ("Plant / line / asset / tag", " / ".join(", ".join(x) if x else "*" for x in (f.plants, f.lines, f.assets, f.tags))),
           ("Batch", ", ".join(f.batches) or "*"),
           ("Date range", f"{f.start or 'start of data'} → {f.end or 'end of data'}"),
           ("Source", "Snowflake GOLD tables; no values are imputed")]
    return sel + (extra or [])


def _stat_tables(s: dict) -> list[Table_]:
    rows = [["Count (n)", s["n"]], ["Missing/invalid removed", s["n_missing"]], ["Mean", s["mean"]], ["Median", s["median"]],
            ["Mode", s["mode"]], ["Minimum", s["min"]], ["Maximum", s["max"]], ["Range", s["range"]], ["Variance (sample)", s["variance"]],
            ["Std deviation (sample)", s["std"]], ["Skewness", s["skewness"]], ["Excess kurtosis", s["kurtosis"]],
            ["Q1", s["q1"]], ["Median (Q2)", s["q2"]], ["Q3", s["q3"]], ["IQR", s["iqr"]]]
    return [Table_("Descriptive statistics", ["Statistic", "Value"], rows),
            Table_("Percentiles", ["Percentile", "Value"], [[k.upper(), v] for k, v in s["percentiles"].items()])]


def _statistical(f, parameter, o, user) -> ReportDoc:
    r = an.statistics_analysis(f, parameter)
    d = an.distribution_analysis(f, parameter, o)["distribution"] if r["statistics"]["n"] >= 3 else None
    sec = Section("Statistical summary", [f"{parameter.upper()}: {r['statistics']['n']} readings, {r['first']} to {r['last']}."] + r["notes"],
                  _stat_tables(r["statistics"]))
    if d:
        sec.images.append(histogram_image(d["histogram"]))
        sec.tables.append(Table_("Normality tests", ["Test", "Statistic", "p-value", "Normal?"],
                                 [[t["test"], t["statistic"], t["p_value"], t["normal"]] for t in d["normality"]["tests"]]))
    return ReportDoc("Statistical Report", _meta("Statistical", f, parameter, user), [sec])


def _chart_sections(res: dict, spec=None) -> list[Section]:
    out = []
    for name, c in res["charts"].items():
        sec = Section(f"{name} chart", [f"{c['n_points']} points; {len(c['out_of_control'])} outside the control limits."])
        sec.images.append(chart_image(name, c, spec if name == res["primary"] else None))
        lim = [[name, c["ucl"][-1], c["cl"][-1], c["lcl"][-1]]] if c["ucl"] else []
        sec.tables.append(Table_("Control limits (last point)", ["Chart", "UCL", "CL", "LCL"], lim))
        ooc = [[c["labels"][i] if i < len(c["labels"]) else i, i, c["points"][i], c["ucl"][i], c["lcl"][i]] for i in c["out_of_control"]]
        sec.tables.append(Table_("Out-of-control points", ["Time", "Index", "Value", "UCL", "LCL"], ooc))
        sec.tables.append(Table_(f"{name} chart data", ["Time", "Index", "Value", "UCL", "CL", "LCL", "Out of control"],
                                 [[c["labels"][i] if i < len(c["labels"]) else None, i, c["points"][i], c["ucl"][i], c["cl"][i], c["lcl"][i],
                                   "YES" if i in set(c["out_of_control"]) else ""] for i in range(c["n_points"])]))
        out.append(sec)
    return out


def _control_chart(f, parameter, o, user) -> ReportDoc:
    res = an.limits_analysis(f, parameter, o)
    secs = [Section("Chart settings", [f"Chart: {o.chart}" + (f", subgroup size {o.subgroup_size}" if o.subgroup_size else "")] + res["notes"],
                    [Table_("Specification and assessment", ["Item", "Value"],
                            [["USL", res["spec"]["usl"]], ["LSL", res["spec"]["lsl"]], ["Target", res["spec"]["target"]]] +
                            [[k, v] for k, v in res["assessment"].items()])])]
    return ReportDoc("Control Chart Report", _meta("Control chart", f, parameter, user), secs + _chart_sections(res, res["spec"]))


def _capability(f, parameter, o, user) -> ReportDoc:
    res = an.capability_analysis(f, parameter, o)
    c = res["capability"]
    idx = [[k.upper(), c[k]] for k in ("cp", "cpk", "cpu", "cpl", "pp", "ppk")]
    perf = [["PPM observed (below LSL)", c["ppm_observed_below"]], ["PPM observed (above USL)", c["ppm_observed_above"]],
            ["PPM observed (total)", c["ppm_observed_total"]], ["PPM expected (overall sigma)", c["ppm_expected_overall"]],
            ["PPM expected (within sigma)", c["ppm_expected_within"]], ["Yield observed %", c["yield_observed"]],
            ["Yield expected %", c["yield_expected"]]]
    base = [["n", c["n"]], ["Mean", c["mean"]], ["USL", c["usl"]], ["LSL", c["lsl"]], ["Target", c["target"]],
            ["Sigma overall", c["sigma_overall"]], ["Sigma within", c["sigma_within"]], ["Within-sigma method", c["sigma_within_method"]]]
    sec = Section("Process capability", res["notes"] + c["warnings"],
                  [Table_("Process", ["Item", "Value"], base), Table_("Capability indices", ["Index", "Value"], idx),
                   Table_("Performance", ["Measure", "Value"], perf)])
    d = an.distribution_analysis(f, parameter, an.ChartOptions())["distribution"]
    sec.images.append(histogram_image(d["histogram"], {"usl": c["usl"], "lsl": c["lsl"], "target": c["target"]}))
    if c["percentile_method"]:
        sec.tables.append(Table_("Percentile method (non-normal data)", ["Item", "Value"], [[k, v] for k, v in c["percentile_method"].items()]))
    return ReportDoc("Process Capability Report", _meta("Capability", f, parameter, user), [sec])


def _quality(f, parameter, o, user) -> ReportDoc:
    ps = data_service.production_summary(f)
    if not ps.total_rows:
        raise UnprocessableError("No production/quality samples match the selection")
    rate = ps.defective_count / ps.sample_size if ps.sample_size and ps.defective_count is not None else None
    totals = [["Samples", ps.total_rows], ["Batches", ps.batches], ["Units produced", ps.units_produced], ["Units inspected", ps.sample_size],
              ["Defective units", ps.defective_count], ["Total defects", ps.defect_count],
              ["Defect rate", rate], ["First-pass yield", (1 - rate) if rate is not None else None],
              ["First sample", str(ps.first)], ["Last sample", str(ps.last)]]
    secs = [Section("Quality summary", [], [Table_("Totals", ["Measure", "Value"], totals)])]
    try:
        charts = an.build_charts(f, None, an.ChartOptions(chart="P"))
        res = {"charts": charts[0], "primary": charts[1]}
        secs += _chart_sections(res)
    except UnprocessableError as e:
        secs[0].paragraphs.append(f"P chart not available: {e.message}")
    return ReportDoc("Quality Report", _meta("Quality", f, None, user), secs)


def _spc(f, parameter, o, user) -> ReportDoc:
    stats = _statistical(f, parameter, o, user).sections[0]
    ch = an.limits_analysis(f, parameter, an.ChartOptions(**{**o.model_dump(), "chart": "IMR" if o.chart in ("P", "NP", "C", "U") else o.chart}))
    viol = an.violations_analysis(f, parameter, an.ChartOptions(**{**o.model_dump(), "chart": ch["chart"]}))
    vs = Section("Rule violations", [f"{viol['summary']['total']} violation(s) on {viol['summary']['points_flagged']} point(s)."],
                 [Table_("Violations", ["Time", "Parameter", "Observed value", "Rule", "Type", "Severity"],
                         [[v["timestamp"], v["parameter"], v["observed_value"], f"{v['rule_id']}: {v['name']}", v["violation_type"], v["severity"]]
                          for v in viol["violations"]])])
    secs = [stats] + _chart_sections(ch, ch["spec"])[:1] + [vs]
    if o.usl is not None or o.lsl is not None:
        secs += _capability(f, parameter, o, user).sections
    d = dash.build(f)
    head = Section("Overall status", [f"{d['status'].replace('_', ' ')}: {d['status_reason']}"],
                   [Table_("Parameters", ["Parameter", "n", "Mean", "Std", "Status", "Violations"],
                           [[c["parameter"], c["n"], c["mean"], c["std"], c["status"], c["violations"]] for c in d["parameters"]])])
    return ReportDoc("SPC Report", _meta("SPC", f, parameter, user), [head] + secs)


BUILDERS = {"spc": _spc, "control_chart": _control_chart, "capability": _capability, "quality": _quality, "statistical": _statistical}


def build(kind: str, f: DataFilters, parameter: str | None, options: dict | None, user) -> ReportDoc:
    if kind not in BUILDERS:
        raise UnprocessableError(f"Unknown report type '{kind}'", {"allowed": sorted(BUILDERS)})
    if kind != "quality" and not parameter:
        raise UnprocessableError("'parameter' is required for this report")
    return BUILDERS[kind](f, parameter, _opts(options), user)


# ---------------------------------------------------------------------------------------------- renderers
def _cell(v):
    if v is None:
        return ""
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return fmt(v)
    return str(v)


def to_pdf(doc: ReportDoc) -> bytes:
    buf = io.BytesIO()
    pdf = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
                            title=doc.title, author="SPC Analytics Platform")
    ss = getSampleStyleSheet()
    story = [Paragraph(doc.title, ss["Title"])]
    story.append(_table([["Field", "Value"]] + [[k, Paragraph(str(v), ss["BodyText"])] for k, v in doc.meta], [45 * mm, 135 * mm], header=True))
    for sec in doc.sections:
        story += [Spacer(1, 6 * mm), Paragraph(sec.heading, ss["Heading2"])]
        story += [Paragraph(p.replace("&", "&amp;").replace("<", "&lt;"), ss["BodyText"]) for p in sec.paragraphs]
        for img in sec.images:
            story += [Spacer(1, 2 * mm), Image(io.BytesIO(img), width=180 * mm, height=64 * mm)]
        for t in sec.tables:
            if not t.rows:
                continue
            story += [Spacer(1, 3 * mm), Paragraph(t.title, ss["Heading4"])]
            shown = t.rows[:PDF_MAX_TABLE_ROWS]
            width = 180 * mm / len(t.columns)
            story.append(_table([t.columns] + [[_cell(c) for c in r] for r in shown], [width] * len(t.columns), header=True))
            if len(t.rows) > len(shown):
                story.append(Paragraph(f"Showing the first {len(shown)} of {len(t.rows)} rows; the Excel export contains all rows.", ss["Italic"]))
    pdf.build(story)
    return buf.getvalue()


def _table(data, widths, header=False):
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    t.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                           ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    return t


def to_xlsx(doc: ReportDoc) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Report"
    ws["A1"] = doc.title
    ws["A1"].font = Font(bold=True, size=14)
    r = 3
    for k, v in doc.meta:
        ws.cell(r, 1, k).font = Font(bold=True)
        ws.cell(r, 2, str(v))
        r += 1
    used = {"Report"}
    for si, sec in enumerate(doc.sections):
        for p in sec.paragraphs:
            r += 1
        for ti, t in enumerate(sec.tables):
            name = f"{si + 1}.{ti + 1} {t.title}"[:31].replace("/", "-").replace(":", "-")
            while name in used:
                name = name[:28] + f"_{len(used)}"
            used.add(name)
            sh = wb.create_sheet(name)
            sh.append(t.columns)
            for c in sh[1]:
                c.font = Font(bold=True)
                c.fill = PatternFill("solid", fgColor="E2E8F0")
            for row in t.rows:
                sh.append([("yes" if v else "no") if isinstance(v, bool) else v for v in row])
            for i, col in enumerate(t.columns, 1):
                sh.column_dimensions[get_column_letter(i)].width = max(12, min(40, len(str(col)) + 4))
            sh.freeze_panes = "A2"
    r += 1
    ws.cell(r, 1, "Notes").font = Font(bold=True)
    for sec in doc.sections:
        for p in sec.paragraphs:
            r += 1
            ws.cell(r, 1, p).alignment = Alignment(wrap_text=False)
    ws.column_dimensions["A"].width = 32
    ws.column_dimensions["B"].width = 80
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
